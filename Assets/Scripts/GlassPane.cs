// ============================================================
// GlassPane.cs —— 透光玻璃：光能穿过，人能站上去
//
// 挂在哪：一块玻璃（需要 Collider2D）
//
// 【它靠图层而不是靠代码来透光】
//   光照的遮挡只查 Light Zone 上的 Blocker Layer（默认只勾 Ground）。
//   所以把玻璃放到【Glass 层】，光就自然穿过去了 —— 不需要在光里写特例。
//
//   三层各管一件事：
//     Ground  挡光 + 挡路        墙、地板、瓦片
//     Glass   只挡路，不挡光      这块玻璃、天窗玻璃、水
//     Default 都不挡              机关、触发器
//
// 【关于"影子能不能穿"】
//   那是一件独立的事，由这个组件的 passableInShadow 控制：
//     勾上   = 影子能穿过去（默认）
//     不勾   = 谁都得站上去，玻璃变成一块实心板
//
//   于是这块玻璃同时说三句话，而且互不矛盾：
//     挡身体   实体是实体，过不去
//     不挡光   光只查 Ground 层，玻璃在 Glass 层
//     不挡影子 影子不是实体，穿过去
//   这三句加起来就是"玻璃"这个东西本身。
//
// 【它顺手多出来的玩法】
//   玻璃是实心的，所以它可以当平台、当天花板。
//   如果把它放在灯和地面之间，光会穿过它照到地上，
//   于是出现一种很干净的关卡结构：
//     "光从上面穿过玻璃照下来，而角色站在玻璃上，被光照成实体"
//   这个不需要任何新代码，是"图层"和"光照"两条规则碰出来的。
// ============================================================

using UnityEngine;

public class GlassPane : MonoBehaviour
{
    [Tooltip("影子形态能不能穿过。\n" +
             "勾上 = 影子能穿过去（玻璃的门那一面）\n" +
             "不勾 = 谁都过不去，玻璃只是一块能站的实心板")]
    public bool passableInShadow = true;
}
